#[test]
fn at_generated_header_canonical() {
    let (_t, facts) = edge();
    // src/generated/client.ts is also in a `generated` directory; the header wins by precedence.
    let class = get(&facts, "src/generated/client.ts").unwrap();
    assert_eq!(
        class.reason,
        GeneratedReason::Header {
            marker: "@generated".to_owned(),
            line: 1
        }
    );
    assert_eq!(class.confidence, 0.95);
}

