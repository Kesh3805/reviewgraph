#[test]
fn config_exclude_beats_header() {
    let tmp = edge_case_tree();
    let cfg = GeneratedConfig {
        exclude: vec!["src/generated/client.ts".to_owned()],
        include: Vec::new(),
    };
    let facts = classify(tmp.path(), &cfg);
    assert!(get(&facts, "src/generated/client.ts").is_none());
    // An exclude also beats a config include.
    let cfg = GeneratedConfig {
        exclude: vec!["src/app.ts".to_owned()],
        include: vec!["src/**".to_owned()],
    };
    let facts = classify(tmp.path(), &cfg);
    assert!(get(&facts, "src/app.ts").is_none());
    assert!(get(&facts, "src/constants.ts").is_some());
}

#[test]
fn config_include_glob() {
    let tmp = edge_case_tree();
    let cfg = GeneratedConfig {
        include: vec!["packages/a/**".to_owned(), "[".to_owned()],
        exclude: Vec::new(),
    };
    let (inv, _) = walk(tmp.path(), &WalkOptions::default()).unwrap();
    let reader = BoundedReader::new(&inv.root);
    let (ts, _) = detect_tsconfigs(&inv, &reader);
    let attrs = GitAttributesView::from_inventory(&inv, &reader);
    let (facts, warnings) = classify_generated(&inv, &ts, &attrs, &cfg, &reader);
    let class = get(&facts, "packages/a/index.ts").unwrap();
    assert!(matches!(
        class.reason,
        GeneratedReason::ConfigInclude { .. }
    ));
    assert!(warnings.iter().any(|w| w.code == "invalid_generated_glob"));
}

#[test]
fn precedence_reason_is_explainable() {
    let (_t, facts) = edge();
    let reasons: Vec<(String, &str)> = facts
        .files
        .iter()
        .map(|(p, c)| (p.as_str().to_owned(), c.reason.label()))
        .collect();
    insta::assert_yaml_snapshot!(reasons);
}
