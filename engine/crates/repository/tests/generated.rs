#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::Path;

use repository::generated::{
    classify_generated, GeneratedConfig, GeneratedFacts, GeneratedKind, GeneratedReason,
    GitAttributesView,
};
use repository::read::BoundedReader;
use repository::tsconfig::detect_tsconfigs;
use repository::walk::{walk, WalkOptions};
use review_core::location::RepoPath;
use review_test_support::{edge_case_tree, write_file};

fn classify(root: &Path, cfg: &GeneratedConfig) -> GeneratedFacts {
    let (inv, _) = walk(root, &WalkOptions::default()).unwrap();
    let reader = BoundedReader::new(&inv.root);
    let (ts, _) = detect_tsconfigs(&inv, &reader);
    let attrs = GitAttributesView::from_inventory(&inv, &reader);
    classify_generated(&inv, &ts, &attrs, cfg, &reader).0
}

fn get<'a>(
    facts: &'a GeneratedFacts,
    path: &str,
) -> Option<&'a repository::generated::GeneratedClass> {
    facts.files.get(&RepoPath::new(path).unwrap())
}

fn edge() -> (tempfile::TempDir, GeneratedFacts) {
    let tmp = edge_case_tree();
    let facts = classify(tmp.path(), &GeneratedConfig::default());
    (tmp, facts)
}

#[test]
fn dist_dir_generated() {
    let (_t, facts) = edge();
    let class = get(&facts, "dist/bundle.js").unwrap();
    assert_eq!(class.kind, GeneratedKind::Generated);
    assert!(matches!(&class.reason, GeneratedReason::Directory { name } if name == "dist"));
    assert!(get(&facts, "coverage/lcov.info").is_some());
    assert!(facts
        .dirs
        .iter()
        .any(|(d, k, n)| d.as_str() == "dist" && *k == GeneratedKind::Generated && *n == 2));
}

#[test]
fn ts_out_dir_generated() {
    let tmp = tempfile::tempdir().unwrap();
    write_file(
        tmp.path(),
        "tsconfig.json",
        r#"{"compilerOptions":{"outDir":"./compiled"}}"#,
    );
    write_file(tmp.path(), "compiled/main.js", "var a;\n");
    write_file(tmp.path(), "src/main.ts", "export {};\n");
    let facts = classify(tmp.path(), &GeneratedConfig::default());
    let class = get(&facts, "compiled/main.js").unwrap();
    assert!(
        matches!(&class.reason, GeneratedReason::TsOutDir { dir } if dir.as_str() == "compiled")
    );
    assert_eq!(class.confidence, 0.9);
    assert!(get(&facts, "src/main.ts").is_none());
}

