#[test]
fn header_outside_comment_ignored() {
    let tmp = tempfile::tempdir().unwrap();
    write_file(
        tmp.path(),
        "src/a.ts",
        "export const marker = \"@generated\";\nexport const b = \"DO NOT EDIT auto-generated\";\n",
    );
    write_file(tmp.path(), "src/b.ts", "// @generated\nexport {};\n");
    let facts = classify(tmp.path(), &GeneratedConfig::default());
    assert!(get(&facts, "src/a.ts").is_none());
    assert!(get(&facts, "src/b.ts").is_some());
}

#[test]
