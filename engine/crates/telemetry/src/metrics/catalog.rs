//! Renders `docs/operations/metrics-catalog.md` from the catalog table. The committed file must
//! equal this output (`cargo run -p xtask -- metrics-catalog --check`).

use std::fmt::Write as _;

use super::buckets::DURATION_SECONDS;
use super::instruments::CATALOG;
use super::labels::ALLOWED;
use super::rates::WINDOW_DAYS;
use crate::spans::SpanName;

/// The acceptance rate formula, as written in the catalog.
pub const ACCEPTANCE_FORMULA: &str =
    "finding_acceptance_rate = (useful + already_handled) / published_with_feedback";

/// The false-positive rate formula, as written in the catalog.
pub const FALSE_POSITIVE_FORMULA: &str =
    "finding_false_positive_rate = false_positive / published_with_feedback";

/// The full markdown document.
pub fn render_markdown() -> String {
    let mut out = String::new();
    out.push_str("# Metrics catalog\n\n");
    out.push_str(
        "<!-- Generated by `cargo run -p xtask -- metrics-catalog` from\n     engine/crates/telemetry/src/metrics/instruments.rs. Do not edit by hand. -->\n\n",
    );
    out.push_str(
        "Contract for OBS-005. Names are lower_snake_case with unit suffixes; labels come from\nbounded values of the allow-list (",
    );
    out.push_str(&ALLOWED.join(", "));
    out.push_str(
        ").\nIdentifiers (organization, repository, run, commit, path) are never labels; per-tenant\nbreakdowns come from traces and logs. A label value outside its domain is recorded as `other`.\n",
    );
    let buckets: Vec<String> = DURATION_SECONDS.iter().map(|b| format!("{b}")).collect();
    let _ = write!(
        out,
        "Duration histogram buckets (seconds): {}.\n\n",
        buckets.join(", ")
    );
    out.push_str(
        "| Metric | Type | Unit | Labels | Description |\n| --- | --- | --- | --- | --- |\n",
    );
    for spec in CATALOG {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            spec.name,
            spec.kind.as_str(),
            spec.unit,
            spec.labels.join(", "),
            spec.description
        );
    }
    let _ = write!(
        out,
        "\n## Rate formulas\n\nOver a trailing {WINDOW_DAYS}-day window of published findings with any feedback:\n\n- `{ACCEPTANCE_FORMULA}`\n- `{FALSE_POSITIVE_FORMULA}`\n\n",
    );
    let names: Vec<&str> = SpanName::ALL.iter().map(|s| s.as_str()).collect();
    let _ = write!(out, "## Span names\n\n`{}`.\n", names.join(", "));
    out
}
